"""Heavy Trunnion Mount: normalized OpenSCAD STLs -> C# mesh data for the DLL.

Usage: py -I heavy_mesh_to_cs.py <model dir> <out .cs>
Input: <model dir>/materials/*.stl, already canonical (model/stlnorm.py, run by build.ps1).
Three meshes, one submesh per material file:
  Static : static-cast, static-steel, static-bronze  (mantlet frame)
  Moving : moving-cast, moving-steel                  (trunnion frame)
  Pinion : pinion-steel                               (origin on the pinion axis)
Axes: OpenSCAD mm (x right, y forward, z up) -> Unity metres (x, z, y) * 0.001. Swapping y/z is a
mirror, so every triangle's winding is reversed (a, b, c -> a, c, b).
Normals: vertices are shared per position only between faces within CREASE degrees, so cast edges
stay sharp and cylinders stay smooth. Output is deterministic (same STL bytes -> same .cs bytes).
"""
import hashlib, math, os, sys

CREASE = 40.0
MESHES = [
    ('Static', ['static-cast', 'static-steel', 'static-bronze']),
    ('Moving', ['moving-cast', 'moving-steel']),
    ('Pinion', ['pinion-steel']),
]


def read_stl(path):
    tris, verts = [], []
    for line in open(path, encoding='ascii'):
        t = line.split()
        if t and t[0] == 'vertex':
            verts.append(tuple(float(v) for v in t[1:4]))
            if len(verts) == 3:
                tris.append(tuple(verts)); verts = []
    return tris


def to_unity(p):
    return (p[0] * 0.001, p[2] * 0.001, p[1] * 0.001)


def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def norm(a):
    n = math.sqrt(dot(a, a))
    return (a[0] / n, a[1] / n, a[2] / n) if n > 0 else (0.0, 1.0, 0.0)


def build(submeshes):
    """submeshes: list of triangle lists (Unity space, Unity winding). Returns verts, normals, indices per submesh."""
    cos_crease = math.cos(math.radians(CREASE))
    faces = []  # (submesh, (p0, p1, p2), face normal)
    for s, tris in enumerate(submeshes):
        for t in tris:
            faces.append((s, t, norm(cross(sub(t[1], t[0]), sub(t[2], t[0])))))
    key = lambda p: (round(p[0], 7), round(p[1], 7), round(p[2], 7))
    incident = {}
    for f, (_, t, _) in enumerate(faces):
        for c in range(3):
            incident.setdefault(key(t[c]), []).append((f, c))
    corner_vertex = {}
    verts, normals = [], []
    for k in sorted(incident):
        groups = []  # each: [summed normal, representative normal, corners]
        for f, c in sorted(incident[k]):
            fn = faces[f][2]
            for g in groups:
                if dot(g[1], fn) >= cos_crease:
                    g[0] = (g[0][0] + fn[0], g[0][1] + fn[1], g[0][2] + fn[2]); g[2].append((f, c)); break
            else:
                groups.append([fn, fn, [(f, c)]])
        for summed, _, corners in groups:
            idx = len(verts)
            verts.append(faces[corners[0][0]][1][corners[0][1]])
            normals.append(norm(summed))
            for fc in corners:
                corner_vertex[fc] = idx
    indices = [[] for _ in submeshes]
    for f, (s, _, _) in enumerate(faces):
        indices[s].extend(corner_vertex[(f, c)] for c in range(3))
    return verts, normals, indices


def fnum(x, digits):
    s = f'{x:.{digits}f}'.rstrip('0').rstrip('.')
    if s in ('-0', ''): s = '0'
    return s + 'f'


def wrap(items, per_line=12, indent='        '):
    return '\n'.join(indent + ', '.join(items[i:i + per_line]) + ',' for i in range(0, len(items), per_line))


def main():
    model, out = sys.argv[1], sys.argv[2]
    lines = [
        '// <auto-generated> by tests/tools/heavy_mesh_to_cs.py from model/materials/*.stl.',
        '// Do not edit: rerun model/build.ps1, then this script. Unity metres, Unity winding.',
        '// </auto-generated>',
        'namespace SprocketOscillatingTurret;',
        '',
        'internal static class HeavyTrunnionMeshData',
        '{',
        f'    internal const float CreaseDegrees = {fnum(CREASE, 1)};',
    ]
    for name, mats in MESHES:
        subs = []
        for m in mats:
            path = os.path.join(model, 'materials', m + '.stl')
            raw = open(path, 'rb').read()
            tris = [(to_unity(a), to_unity(c), to_unity(b)) for a, b, c in read_stl(path)]
            subs.append(tris)
            const = ''.join(w.capitalize() for w in m.split('-'))
            lines.append(f'    internal const string {const}Sha256 = "{hashlib.sha256(raw).hexdigest()}";')
            lines.append(f'    internal const int {const}Triangles = {len(tris)};')
        verts, normals, indices = build(subs)
        lines.append(f'    internal static readonly string[] {name}Materials = {{ {", ".join(chr(34) + m + chr(34) for m in mats)} }};')
        lines.append(f'    internal static readonly float[] {name}Vertices =')
        lines.append('    {')
        lines.append(wrap([fnum(c, 6) for v in verts for c in v]))
        lines.append('    };')
        lines.append(f'    internal static readonly float[] {name}Normals =')
        lines.append('    {')
        lines.append(wrap([fnum(c, 4) for v in normals for c in v]))
        lines.append('    };')
        lines.append(f'    internal static readonly int[][] {name}Triangles =')
        lines.append('    {')
        for idx in indices:
            lines.append('        new[]')
            lines.append('        {')
            lines.append(wrap([str(i) for i in idx], 24, '            '))
            lines.append('        },')
        lines.append('    };')
        print(f'{name}: {len(verts)} vertices, {sum(len(i) for i in indices) // 3} triangles, submeshes {[len(i) // 3 for i in indices]}')
    lines.append('}')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
