"""Outer convex collision envelopes: <=100 triangles, <=10mm from the detailed convex hull.
No third-party Python packages. A reduced convex vertex set is conservatively expanded to enclose LOD0.
Concavities are intentionally filled, as with OpenSCAD hull(). Bounds expand by <=10mm.
Both all-point inclusion and directed convex-envelope distance are independently tested.
"""
from pathlib import Path
import math, subprocess, sys
sys.path.insert(0,str(Path(__file__).resolve().parent))
from stlcheck import read_stl
ROOT=Path(__file__).resolve().parent
SCAD=r'C:\Program Files\OpenSCAD\openscad.com'
def sub(a,b):return tuple(x-y for x,y in zip(a,b))
def add(a,b):return tuple(x+y for x,y in zip(a,b))
def mul(a,t):return tuple(x*t for x in a)
def dot(a,b):return sum(x*y for x,y in zip(a,b))
def cross(a,b):return (a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0])
def norm(a):return math.sqrt(dot(a,a))
def unit(a):return mul(a,1/norm(a))
def unique(vs):return list({tuple(round(x,6) for x in v):v for v in vs}.values())
def planes(tris):
 c=mul(tuple(map(sum,zip(*(v for t in tris for v in t)))),1/(3*len(tris)))
 out={}
 for a,b,d in tris:
  n=unit(cross(sub(b,a),sub(d,a)));h=dot(n,a)
  if dot(n,c)>h:n=mul(n,-1);h=-h
  out[tuple(round(x,5) for x in (*n,h))]=(n,h)
 return list(out.values())
def distance_triangle(p,a,b,c):
 # Closest point on triangle (Ericson region tests).
 ab,ac,ap=sub(b,a),sub(c,a),sub(p,a);d1,d2=dot(ab,ap),dot(ac,ap)
 if d1<=0 and d2<=0:return norm(ap)
 bp=sub(p,b);d3,d4=dot(ab,bp),dot(ac,bp)
 if d3>=0 and d4<=d3:return norm(bp)
 vc=d1*d4-d3*d2
 if vc<=0 and d1>=0 and d3<=0:return norm(sub(p,add(a,mul(ab,d1/(d1-d3)))))
 cp=sub(p,c);d5,d6=dot(ab,cp),dot(ac,cp)
 if d6>=0 and d5<=d6:return norm(cp)
 vb=d5*d2-d1*d6
 if vb<=0 and d2>=0 and d6<=0:return norm(sub(p,add(a,mul(ac,d2/(d2-d6)))))
 va=d3*d6-d5*d4
 if va<=0 and d4-d3>=0 and d5-d6>=0:return norm(sub(p,add(b,mul(sub(c,b),(d4-d3)/((d4-d3)+(d5-d6))))))
 den=1/(va+vb+vc);return norm(sub(p,add(a,add(mul(ab,vb*den),mul(ac,vc*den)))))
def surface_distance(p,tris):return min(distance_triangle(p,*t) for t in tris)
def qh(vs):
 a=vs[0];b=max(vs,key=lambda p:norm(sub(p,a)));c=max(vs,key=lambda p:norm(cross(sub(p,a),sub(b,a))));n=unit(cross(sub(b,a),sub(c,a)));d=max(vs,key=lambda p:abs(dot(n,sub(p,a))))
 center=mul(add(add(a,b),add(c,d)),.25)
 def face(a,b,c):
  if dot(cross(sub(b,a),sub(c,a)),sub(center,a))>0:b,c=c,b
  return (a,b,c)
 faces=[face(a,b,c),face(a,c,d),face(a,d,b),face(b,d,c)]
 for v in vs:
  visible=[f for f in faces if dot(unit(cross(sub(f[1],f[0]),sub(f[2],f[0]))),sub(v,f[0]))>1e-6]
  if not visible:continue
  edges={}
  for f in visible:
   for a,b in zip(f,f[1:]+f[:1]):
    if (b,a) in edges:edges.pop((b,a))
    else:edges[(a,b)]=1
  faces=[f for f in faces if f not in visible]+[face(a,b,v) for a,b in edges]
 return faces

def build(part):
 folder=ROOT/'parts';exact=folder/(part+'-exact.stl')
 src=folder/(part+'-exact.scad');src.write_text('hull() import("'+part+'-lod0.stl");\n')
 subprocess.run([SCAD,'-o',str(exact),str(src)],check=True,capture_output=True)
 detailed=read_stl(exact);vs=unique(v for t in detailed for v in t)
 candidates=[]
 for relative in (False,True):
  chosen=unique([max(vs,key=lambda v:sgn*v[i]) for i in range(3) for sgn in (-1,1)])
  center=mul(tuple(map(sum,zip(*vs))),1/len(vs))
  while len(chosen)<52:
   ps=planes(qh(chosen))
   if relative:
    def error(v):return max((dot(n,v)-dot(n,center))/max(.001,h-dot(n,center)) for n,h in ps)
   else:
    def error(v):return max(dot(n,v)-h for n,h in ps)
   worst=max((v for v in vs if v not in chosen),key=error,default=None)
   if worst is None:break
   chosen.append(worst)
  ps=planes(qh(chosen))
  # Centroid must be strictly inside the selected hull; raw strategy handles unusual initial clouds.
  if min(h-dot(n,center) for n,h in ps)<=0:continue
  factor=max((max(dot(n,v) for v in vs)-dot(n,center))/(h-dot(n,center)) for n,h in ps)+.00001
  out=[add(center,mul(sub(v,center),factor)) for v in chosen]
  distance=max(surface_distance(v,detailed) for v in out)
  candidates.append((distance,out))
 distance,out=min(candidates,key=lambda c:c[0]);tris=qh(out)
 if distance>10 or len(tris)>100:raise RuntimeError(f'{part}: tolerance/budget {distance}mm, {len(tris)} triangles')
 ids={v:i for i,v in enumerate(out)}
 path=folder/(part+'-hull.scad')
 path.write_text('// Generated by build_hulls.py; conservative envelope of LOD0, <=100 triangles, <=10mm from its convex hull.\npolyhedron(points='+str([list(v) for v in out])+',faces='+str([[ids[v] for v in reversed(t)] for t in tris])+',convexity=10);\n')
 subprocess.run([SCAD,'-o',str(folder/(part+'-hull.stl')),str(path)],check=True,capture_output=True)
 print(f'{part}: {len(read_stl(folder/(part+"-hull.stl")))} tris, convex-envelope margin {distance:.4f}mm',flush=True)

if __name__=='__main__':
 for part in ['start','pair','output','turbo','turbo-outboard']:build(part)
