"""Render the integrated casing against the V12/Renk mockup frame.

The casing STLs are written by `Checks.dll --casing-preview`, which decodes the
same .meshbin payloads that are embedded in the DLL and applies the production
CasingFit. This script only turns those exact warped triangles into one PNG and
writes the reproducible OpenSCAD view with dimension lines.

Run from the mod root (after building tests/Checks.csproj in Release):
  py -I -B mtu-model/model/preview-casing-fit.py
"""
from pathlib import Path
import json, subprocess, sys

ROOT = Path(__file__).resolve().parents[1]  # the mod root
MODEL = Path(__file__).resolve().parent
PREVIEW = MODEL / 'preview'
SHOTS = MODEL / 'shots'
CHECKS = ROOT / 'tests/bin/Release/net6.0/Checks.dll'
SCAD = r'C:\Program Files\OpenSCAD\openscad.com'

for name in ('casing-fit-v12-renk-lod0.stl', 'casing-fit-v12-renk-lod1.stl',
             'casing-fit-v12-renk.json'):
    if not (PREVIEW / name).exists():
        result = subprocess.run(['dotnet', str(CHECKS), '--casing-preview', str(PREVIEW)],
                                cwd=ROOT, capture_output=True, text=True)
        if result.returncode != 0:
            sys.stderr.write(result.stdout + result.stderr)
            raise SystemExit(result.returncode)
        break

data = json.loads((PREVIEW / 'casing-fit-v12-renk.json').read_text(encoding='utf-8'))
ew, eh = data['engine']['size'][0], data['engine']['size'][1]
gw, gh = data['gearbox']['size'][0], data['gearbox']['size'][1]
ey = data['engine']['centre'][2] + data['engine']['size'][2] / 2
gy = data['gearbox']['centre'][2] + data['gearbox']['size'][2] / 2
cs, ce = data['casing']['start'], data['casing']['end']
# Vehicle-local scene used by view-casing-pack.scad (millimetres).
N, d = 12, 3.97
k = d ** (1 / 3)
n = N / 2
rear = (n * 60 + 245) * k * .9

scad = f'''// Generated by mtu-model/model/preview-casing-fit.py. Do not edit.
// Exact production CasingFit applied to the embedded LOD0 payload, V12 3.97 L + one Renk box.
// OpenSCAD frame: x=side, y=longitudinal, z=up. Casing STL came from the DLL meshbin -> CasingFit.Warp.
N={N};d={d};k=pow(d,1/3);n=N/2;rear={rear:.6f};lod=0;
module part(name){{import(str("parts/",name,"-lod",lod,".stl"),convexity=10);}}
module engine(){{scale([k,k*.9,k])translate([0,-n*60,0]){{
 part("start");for(i=[0:n-1])translate([0,i*120,0])part("pair");
 translate([0,n*120,0]){{part("output");part("turbo");}}
}}}}
module renk(){{
 part("tra-input");for(s=[-1,1]){{
  for(i=[0:3])translate([s*(160+i*85),0,0])part("tra-shroud");
  translate([s*415,0,0])if(s<0)part("tra-output-l");else part("tra-output-r");
 }}
}}
module rod(a,b,r=4){{hull(){{translate(a)sphere(r);translate(b)sphere(r);}}}}
module label(t,p,s=90){{translate(p)rotate([90,0,0])linear_extrude(2)text(t,size=s,halign="left",valign="center");}}
color([.73,.77,.78])engine();
color([.61,.65,.66])translate([0,rear+430,65])scale([1,.95,1.35])renk();
color([.41,.47,.37])import("preview/casing-fit-v12-renk-lod0.stl",convexity=10);
// Casing starts at the engine rear face and covers the Renk box.
color([1,.85,0]){{
 rod([-{ew/2:.3f},{ey:.3f},{eh+35:.3f}],[{ew/2:.3f},{ey:.3f},{eh+35:.3f}]);
 rod([-{ew/2-45:.3f},{ey:.3f},0],[-{ew/2-45:.3f},{ey:.3f},{eh:.3f}]);
 rod([-{gw/2:.3f},{gy:.3f},{gh+35:.3f}],[{gw/2:.3f},{gy:.3f},{gh+35:.3f}]);
 rod([{gw/2+45:.3f},{gy:.3f},0],[{gw/2+45:.3f},{gy:.3f},{gh:.3f}]);
 rod([0,{cs:.3f},-35],[0,{ce:.3f},-35]);
 // Front-facing legend, kept outside the model so the exact casing stays visible.
 label("motor rear B {ew/1000:.3f} m   H {eh/1000:.3f} m",[-1500,-1700,1450]);
 label("Renk box   B {gw/1000:.3f} m   H {gh/1000:.3f} m",[-1500,-1700,1300]);
 label("casing L   {(ce-cs)/1000:.3f} m",[-1500,-1700,1150]);
 label("LOD0 556 tri / LOD1 152 tri",[-1500,-1700,1000]);
}}
'''
(MODEL / 'view-casing-fit.scad').write_text(scad, encoding='utf-8')
SHOTS.mkdir(exist_ok=True)
result = subprocess.run([SCAD, '-o', str(SHOTS / 'casing-fit-v12-renk.png'),
                         '--imgsize=1200,800', '--camera=-1.3,-1,0.85,0,0,0',
                         '--viewall', '--autocenter', '--colorscheme=Tomorrow',
                         str(MODEL / 'view-casing-fit.scad')], cwd=MODEL,
                        capture_output=True, text=True)
log = result.stdout + result.stderr
(MODEL / 'logs/casing-fit-render.txt').write_text(log, encoding='utf-8')
if result.returncode != 0:
    sys.stderr.write(log)
    raise SystemExit(result.returncode)
png = SHOTS / 'casing-fit-v12-renk.png'
if not png.exists() or png.stat().st_size < 10000:
    raise SystemExit('missing or empty casing preview PNG: ' + str(png))
tris = sum(1 for line in (PREVIEW / 'casing-fit-v12-renk-lod0.stl').read_text(encoding='ascii').splitlines()
           if line.strip().startswith('facet normal'))
if tris != 556:
    raise SystemExit(f'preview STL has {tris} triangles, expected 556')
print(f'PASS casing V12/Renk preview: {png} ({png.stat().st_size} bytes), LOD0 {tris} triangles, '
      f'casing {(ce-cs)/1000:.3f} m')
