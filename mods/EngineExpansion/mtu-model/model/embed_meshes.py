"""Canonical STL -> compact binary DLL resources, Unity (x,z,y), mm*.001 except normalised casing*1, reversed winding.
Run with --check to compare exact packed bytes AND the generated source hashes to current STLs.
The runtime verifies each packed payload hash before constructing a Unity Mesh.
"""
from pathlib import Path
import hashlib,struct,sys,json
sys.path.insert(0,str(Path(__file__).resolve().parent))
from stlcheck import read_stl
ROOT=Path(__file__).resolve().parent
PROJECT=ROOT.parents[1]  # the mod root (holds Assets/ and Native/)
files=sorted(p for p in (ROOT/'parts').glob('*.stl') if '-exact' not in p.name and (p.stem.endswith(('lod0','lod1','hull'))) and not p.stem.startswith('twin-bridge'))
lines=['// Generated by mtu-model/model/embed_meshes.py. Do not edit.','namespace SprocketEngineExpansion.Native;','internal static class PowerpackMeshManifest','{','    internal static readonly (string Name,string StlHash,string DataHash,int Triangles)[] Entries=new[]','    {']
manifest=[];bad=[]
for p in files:
 unit_scale=1.0 if p.stem.startswith("casing-") else .001
 ts=read_stl(p);vertices=[];indices=[];lookup={}
 for tri in ts:
  for v in (tri[0],tri[2],tri[1]):
   q=tuple(struct.unpack('<f',struct.pack('<f',x*unit_scale))[0] for x in (v[0],v[2],v[1]))
   if q not in lookup:lookup[q]=len(vertices);vertices.append(q)
   indices.append(lookup[q])
 data=struct.pack('<II',len(vertices),len(indices))+b''.join(struct.pack('<fff',*v) for v in vertices)+struct.pack('<'+'I'*len(indices),*indices)
 stlhash=hashlib.sha256(p.read_bytes()).hexdigest();datahash=hashlib.sha256(data).hexdigest()
 target=PROJECT/'Assets'/(p.stem+'.meshbin')
 if '--check' in sys.argv:
  if not target.exists() or target.read_bytes()!=data:bad.append(str(target))
 else:target.parent.mkdir(exist_ok=True);target.write_bytes(data)
 lines.append(f'        ("{p.stem}","{stlhash}","{datahash}",{len(ts)}),')
 manifest.append(dict(name=p.stem,stl_sha256=stlhash,payload_sha256=datahash,triangles=len(ts),vertices=len(vertices),unit_scale=unit_scale))
lines+=['    };','}'];source='\n'.join(lines)+'\n';target=PROJECT/'Native/PowerpackMeshManifest.g.cs'
if '--check' in sys.argv:
 if not target.exists() or target.read_text(encoding='utf-8-sig')!=source:bad.append(str(target))
else:
 target.write_text(source,encoding='utf-8');(ROOT/'logs/mesh-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(('FAIL '+str(bad)) if bad else f'PASS {len(files)} STL hashes and exact Unity mesh payloads')
sys.exit(bool(bad))
