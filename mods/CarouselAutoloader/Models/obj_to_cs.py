"""Carousel Autoloader 0.2.29: approved carousel OBJ models -> compact C# mesh data.

Usage: py -I Models/obj_to_cs.py <carousel_t72.obj> <carousel_t80.obj> <carousel-source-dir>

Source models (approved 2026-11-05, "Goed, bouw ze in"):
  2026-11-05/carousel-mistral/t72/claude-fix/carousel_t72.obj
  2026-11-05/carousel-mistral/t80/claude-fix/carousel_t80.obj
Each OBJ has exactly five groups (cassette, projectiel, lading, naaf, lift), metres, +Y up, triangles.
The OBJs are copied to <source>/Models/ so the test can compare the embedded data with them
(SHA256 of the file plus an independent re-parse of positions, normals and triangles).

Per group every distinct (v, vn) pair becomes one vertex, in order of first use; triangles keep
the OBJ order and winding (cross(b-a, c-a) points outward, which is also Unity's front face for
these raw coordinates). Deterministic: same OBJ bytes -> same C# file.
"""
import hashlib, os, shutil, sys

GROUPS = [("cassette", "Cassette"), ("projectiel", "Projectile"), ("lading", "Charge"), ("naaf", "Hub"), ("lift", "Lift")]
STYLES = [("T72", "t72", "T-72 style: projectile below, charge lying above it"),
          ("T80", "t80", "T-80 style: projectile lying, charge upright at the outer edge")]


def parse(path):
    v, vn, groups, current = [], [], {}, None
    with open(path, encoding="utf-8") as f:
        for line in f:
            p = line.split()
            if not p:
                continue
            if p[0] == "v":
                v.append(p[1:4])
            elif p[0] == "vn":
                vn.append(p[1:4])
            elif p[0] == "g":
                current = p[1]
                if current in groups:
                    raise SystemExit(f"{path}: group {current} appears twice")
                groups[current] = []
            elif p[0] == "f":
                corners = [q.split("/") for q in p[1:]]
                if len(corners) != 3:
                    raise SystemExit(f"{path}: face with {len(corners)} corners, expected triangles")
                groups[current].append([(int(c[0]), int(c[2])) for c in corners])
    names = [g for g, _ in GROUPS]
    if list(groups) != names:
        raise SystemExit(f"{path}: groups {list(groups)}, expected {names}")
    return v, vn, groups


def fmt(text):
    s = ("%.6f" % float(text)).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "", "0") else s + "f"


def convert(v, vn, faces):
    ids, pos, nor, idx = {}, [], [], []
    for face in faces:
        for vi, ni in face:
            key = (vi, ni)
            if key not in ids:
                ids[key] = len(ids)
                pos.extend(v[vi - 1])
                nor.extend(vn[ni - 1])
            idx.append(ids[key])
    return pos, nor, idx


def main(t72, t80, source):
    models = os.path.join(source, "Models")
    os.makedirs(models, exist_ok=True)
    out = ["// <auto-generated> by Models/obj_to_cs.py from the approved carousel OBJ models (2026-11-05, claude-fix).",
           "// Do not edit: re-run  py -I Models/obj_to_cs.py <carousel_t72.obj> <carousel_t80.obj> <this folder>.",
           "// Metres, +Y up. cassette/projectiel/lading: slot frame (origin outer edge, bottom, centre line; -Z to the",
           "// carousel centre, X tangential). naaf: origin carousel centre, bottom. lift: origin centre of the foot, ram +Z.",
           "// Positions and normals x,y,z per vertex (one vertex per OBJ v/vn pair), triangles as index triples.",
           "namespace SprocketCarouselAutoloader;", "",
           "public sealed record CarouselPart(string Name, float[] Positions, float[] Normals, int[] Indices)",
           "{", "    public int Triangles => Indices.Length / 3;", "    public int Vertices => Positions.Length / 3;", "}", "",
           "public sealed record CarouselStyleData(string Name, string ObjFile, string ObjSha256,",
           "    CarouselPart Cassette, CarouselPart Projectile, CarouselPart Charge, CarouselPart Hub, CarouselPart Lift)",
           "{", "    public CarouselPart[] Parts => new[] { Cassette, Projectile, Charge, Hub, Lift };", "}", "",
           "public static class CarouselModelData", "{"]
    for (field, style, text), path in zip(STYLES, (t72, t80)):
        data = open(path, "rb").read()
        sha = hashlib.sha256(data).hexdigest().upper()
        target = f"carousel_{style}.obj"
        shutil.copyfile(path, os.path.join(models, target))
        v, vn, groups = parse(path)
        out.append(f"    // {text}. Source SHA256 {sha}.")
        out.append(f'    public static readonly CarouselStyleData {field} = new("{style}", "{target}", "{sha}",')
        parts = []
        for name, _ in GROUPS:
            pos, nor, idx = convert(v, vn, groups[name])
            parts.append((name, pos, nor, idx))
            print(f"{style} {name}: {len(idx) // 3} triangles, {len(pos) // 3} vertices")
        for i, (name, pos, nor, idx) in enumerate(parts):
            end = ");" if i == len(parts) - 1 else ","
            out.append(f'        new CarouselPart("{name}",')
            out.append("            new float[] {" + ",".join(fmt(x) for x in pos) + "},")
            out.append("            new float[] {" + ",".join(fmt(x) for x in nor) + "},")
            out.append("            new int[] {" + ",".join(str(i) for i in idx) + "})" + end)
        print(f"{style}: sha {sha[:16]}")
    out.append("    public static readonly CarouselStyleData[] All = { T72, T80 };")
    out.append("}")
    with open(os.path.join(source, "CarouselModelData.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3])
