from pathlib import Path
import importlib.util, hashlib
root=Path.cwd()
spec=importlib.util.spec_from_file_location('stl',root/'Models/stl_to_cs.py'); mod=importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
out=['// <auto-generated> by Models/generate_belt_meshes.py using stl_to_cs.py.', 'namespace SprocketCarouselAutoloader;', '', 'public static class BeltMeshData', '{']
for field,name in [('Box','belt-box'),('Link','belt-link-lo'),('Chute','belt-chute')]:
    raw,tris=mod.read_stl(root/'Models'/(name+'.stl')); pos,idx=mod.convert(tris,40)
    out += [f'    public static readonly UnitMesh {field} = new("{name}", "{hashlib.sha256(raw).hexdigest().upper()}", {len(tris)},', '        new float[] {'+','.join(mod.fmt(v) for v in pos)+'},', '        new int[] {'+','.join(map(str,idx))+'});']
    print(field,len(tris),len(idx)//3)
out+=['    public static readonly UnitMesh[] All = { Box, Link, Chute };','}']
(root/'BeltMeshData.cs').write_text('\n'.join(out)+'\n')
