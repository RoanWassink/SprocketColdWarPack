"""Carousel Autoloader 0.2.23/0.2.24: OpenSCAD STL parts -> compact C# mesh data.

Usage: py -I stl_to_cs.py <parts-dir> <carousel-source-dir>
Reads <parts-dir>/<name>.stl for every part below, drops degenerate facets, shares vertices
within a smoothing group (crease angle below), and writes <source>/AutoloaderMeshData.cs.
The STL files are copied to <source>/Models/ so the test can check the embedded data against
the export by SHA256. Deterministic: same STL bytes -> same C# file.
"""
import hashlib, math, os, shutil, struct, sys

PARTS = [  # (C# name, stl file, crease angle in degrees, description)
    ("Round12", "round12", 50, "complete round, 12 sides, rim/groove/band/ogive (fine)"),
    ("Round8", "round8", 50, "complete round, 8 sides, same profile (medium)"),
    ("Round8Coarse", "round8c", 50, "complete round, 8 sides, six-point profile (coarse)"),
    ("Projectile12", "projectile12", 50, "two-piece projectile, 12 sides (fine)"),
    ("Projectile8", "projectile8", 50, "two-piece projectile, 8 sides (medium/coarse)"),
    ("Charge12", "charge12", 50, "two-piece charge case with plug, 12 sides (fine)"),
    ("Charge8", "charge8", 50, "two-piece charge case with plug, 8 sides (medium/coarse)"),
    ("Cradle", "cradle", 40, "bustle cradle (goot) per round cell, unit length"),
    ("Clamp", "clamp", 40, "bustle cross-clamp saddle per top cell, unit width"),
    ("CradleLite", "cradle8", 40, "bustle cradle, 8-sided cut-out matching the 8-sided rounds (light level)"),
    ("ClampLite", "clamp8", 40, "bustle cross-clamp saddle, 8-sided cut-out (light level)"),
    ("Trough", "trough", 40, "feed trough (laadgoot) profile, unit length"),
    ("RamHead", "ramhead", 50, "rammer head, unit calibre"),
    ("HubCap", "hubcap", 40, "drum end-plate hub with bolts, unit radius and thickness"),
]

def read_stl(path):
    data = open(path, "rb").read()
    tris = []
    if data[:5] == b"solid" and b"facet" in data[:400]:
        cur = []
        for line in data.decode("ascii").splitlines():
            p = line.split()
            if p and p[0] == "vertex":
                cur.append(tuple(float(v) for v in p[1:4]))
                if len(cur) == 3:
                    tris.append(tuple(cur)); cur = []
    else:
        n = struct.unpack("<I", data[80:84])[0]
        for i in range(n):
            v = struct.unpack("<12f", data[84 + 50 * i: 84 + 50 * i + 48])
            tris.append(((v[3], v[4], v[5]), (v[6], v[7], v[8]), (v[9], v[10], v[11])))
    return data, tris

def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def cross(u, w): return (u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2], u[0] * w[1] - u[1] * w[0])
def norm(v):
    l = math.sqrt(v[0] ** 2 + v[1] ** 2 + v[2] ** 2)
    return (v[0] / l, v[1] / l, v[2] / l) if l > 0 else (0.0, 0.0, 0.0)

def convert(tris, crease):
    key = lambda v: (round(v[0], 6), round(v[1], 6), round(v[2], 6))
    faces = []
    for t in tris:
        n = cross(sub(t[1], t[0]), sub(t[2], t[0]))
        if math.sqrt(n[0] ** 2 + n[1] ** 2 + n[2] ** 2) / 2 <= 1e-12:
            continue
        faces.append((tuple(key(v) for v in t), norm(n)))
    limit = math.cos(math.radians(crease))
    groups = {}  # position -> list of (normal of first member, vertex id)
    positions, indices = [], []
    for corners, n in faces:
        for p in corners:
            slot = None
            for g in groups.setdefault(p, []):
                if g[0][0] * n[0] + g[0][1] * n[1] + g[0][2] * n[2] >= limit:
                    slot = g[1]; break
            if slot is None:
                slot = len(positions) // 3
                positions.extend(p)
                groups[p].append((n, slot))
            indices.append(slot)
    return positions, indices

def fmt(v):
    s = ("%.6f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s + "f"

def main(parts_dir, source):
    models = os.path.join(source, "Models")
    os.makedirs(models, exist_ok=True)
    out = ["// <auto-generated> by Models/scad/stl_to_cs.py from the OpenSCAD parts in Models/scad/parts.",
           "// Do not edit: change the .scad file, re-export the STL (build-parts.ps1) and regenerate.",
           "// Units: calibre 1 (or radius 1 for the hub); positions x,y,z per vertex, triangles as index triples.",
           "namespace SprocketCarouselAutoloader;", "",
           "public sealed record UnitMesh(string Name, string StlSha256, int StlFacets, float[] Positions, int[] Indices)",
           "{", "    public int Triangles => Indices.Length / 3;", "}", "",
           "public static class AutoloaderMeshData", "{"]
    for name, stl, crease, text in PARTS:
        path = os.path.join(parts_dir, stl + ".stl")
        data, tris = read_stl(path)
        shutil.copyfile(path, os.path.join(models, stl + ".stl"))
        sha = hashlib.sha256(data).hexdigest().upper()
        pos, idx = convert(tris, crease)
        out.append(f"    // {text}: {len(idx) // 3} triangles, {len(pos) // 3} vertices, crease {crease} deg.")
        out.append(f'    public static readonly UnitMesh {name} = new("{stl}", "{sha}", {len(tris)},')
        out.append("        new float[] {" + ",".join(fmt(v) for v in pos) + "},")
        out.append("        new int[] {" + ",".join(str(i) for i in idx) + "});")
        print(f"{name}: {len(tris)} facets -> {len(idx) // 3} triangles, {len(pos) // 3} vertices, sha {sha[:12]}")
    out.append("    public static readonly UnitMesh[] All = {" + ", ".join(p[0] for p in PARTS) + "};")
    out.append("}")
    with open(os.path.join(source, "AutoloaderMeshData.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
