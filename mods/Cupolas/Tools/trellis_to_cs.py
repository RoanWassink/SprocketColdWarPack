"""Convert all cupola OBJs (T-90A + TRELLIS/Blender variants) into CupolaMeshData.cs."""
from pathlib import Path
import hashlib
import math
import struct

ROOT = Path(__file__).resolve().parents[1]


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def length_sq(a):
    return dot(a, a)


def norm(a):
    l = math.sqrt(length_sq(a))
    return (a[0] / l, a[1] / l, a[2] / l) if l > 1e-12 else (0.0, 1.0, 0.0)


def parse_obj_with_uv_wn(path: Path):
    raw_pos, raw_uv, raw_vn = [], [], []
    raw_tris = []
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        p = line.split()
        if not p:
            continue
        if p[0] == "v":
            raw_pos.append((float(p[1]), float(p[2]), float(p[3])))
        elif p[0] == "vt":
            raw_uv.append((float(p[1]), float(p[2])))
        elif p[0] == "vn":
            raw_vn.append(norm((float(p[1]), float(p[2]), float(p[3]))))
        elif p[0] == "f":
            corners = []
            for c in p[1:]:
                parts = c.split("/")
                vi = int(parts[0]) - 1
                ti = int(parts[1]) - 1 if len(parts) > 1 and parts[1] else -1
                ni = int(parts[2]) - 1 if len(parts) > 2 and parts[2] else -1
                corners.append((vi, ti, ni))
            for k in range(1, len(corners) - 1):
                raw_tris.append((corners[0], corners[k], corners[k + 1]))

    vertices, normals, uvs, indices = [], [], [], []
    vmap = {}
    has_uv = len(raw_uv) > 0

    for c0, c1, c2 in raw_tris:
        a, b, c = raw_pos[c0[0]], raw_pos[c1[0]], raw_pos[c2[0]]
        cr = cross(sub(b, a), sub(c, a))
        if length_sq(cr) < 1e-16:
            continue
        fn = norm(cr)
        for vi, ti, ni in (c0, c1, c2):
            vn = raw_vn[ni] if 0 <= ni < len(raw_vn) else fn
            if dot(cr, vn) <= 0:
                vn = fn
            uv = raw_uv[ti] if (has_uv and 0 <= ti < len(raw_uv)) else (0.0, 0.0)
            key = (vi, round(uv[0], 5), round(uv[1], 5), round(vn[0], 4), round(vn[1], 4), round(vn[2], 4))
            if key not in vmap:
                vmap[key] = len(vertices)
                vertices.append(raw_pos[vi])
                normals.append(vn)
                uvs.append(uv)
            indices.append(vmap[key])

    print(f"{path.name}: verts={len(vertices)} tris={len(indices)//3} has_uv={has_uv}")
    return vertices, normals, (uvs if has_uv else None), indices


def make_hidden_door_box():
    cx, cy, cz = 0.0, 0.0, 0.0
    h = 0.06
    corners = [
        (cx - h, cy - h, cz - h), (cx + h, cy - h, cz - h), (cx + h, cy + h, cz - h), (cx - h, cy + h, cz - h),
        (cx - h, cy - h, cz + h), (cx + h, cy - h, cz + h), (cx + h, cy + h, cz + h), (cx - h, cy + h, cz + h),
    ]
    quads = [
        (0, 3, 2, 1, (0, 0, -1)), (4, 5, 6, 7, (0, 0, 1)),
        (0, 1, 5, 4, (0, -1, 0)), (2, 3, 7, 6, (0, 1, 0)),
        (0, 4, 7, 3, (-1, 0, 0)), (1, 2, 6, 5, (1, 0, 0)),
    ]
    verts, ns, inds = [], [], []
    for a, b, c, d, n in quads:
        base = len(verts)
        for idx in (a, b, c, d):
            verts.append(corners[idx])
            ns.append(n)
        inds.extend([base, base + 1, base + 2, base, base + 2, base + 3])
    return verts, ns, None, inds


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def emit_entry(prop_name: str, short_name: str, obj_sha: str, verts, normals, uvs, inds):
    pos = [f32(x) for v in verts for x in v]
    ns = [f32(x) for n in normals for x in n]
    bounds = [f32(f(v[i] for v in verts)) for f in (min, max) for i in range(3)]
    binary = struct.pack("<" + "f" * (len(pos) + len(ns)) + "i" * len(inds), *pos, *ns, *inds)
    data_sha = hashlib.sha256(binary).hexdigest().upper()
    lines = [f'internal static readonly CupolaData {prop_name} = new("{short_name}", "{obj_sha}", "{data_sha}",']
    for arr, ty in ((pos, "float"), (ns, "float"), (inds, "int"), (bounds, "float")):
        vals = ",".join(format(v, ".9g") + "f" if ty == "float" else str(v) for v in arr)
        lines.append(f"new {ty}[] {{{vals}}},")
    if uvs is not None:
        uflat = [f32(x) for u in uvs for x in u]
        uvals = ",".join(format(v, ".9g") + "f" for v in uflat)
        lines.append(f"new float[] {{{uvals}}});")
    else:
        lines.append("null);")
    return lines


def main():
    icon = ROOT / "Assets/approved/t90a-cupola-icon.png"
    out = [
        "// <auto-generated> Tools/trellis_to_cs.py; T-90A + TRELLIS/Blender cupola variants.",
        "#nullable enable",
        "namespace SprocketCupolas;",
        "internal sealed record CupolaData(string Name, string ObjSha256, string DataSha256, float[] Positions, float[] Normals, int[] Indices, float[] Bounds, float[]? Uvs);",
        "internal static class CupolaMeshData {",
        'internal const string IconSha256 = "' + hashlib.sha256(icon.read_bytes()).hexdigest().upper() + '";',
    ]

    entries = [
        ("T90ABase", "base", ROOT / "Assets/approved/t90a_cupola_base.obj"),
        ("T90ADoor", "door", ROOT / "Assets/approved/t90a_cupola_door.obj"),
        ("AbramsBase", "abrams_base", ROOT / "Assets/approved/trellis_cupola_d_base.obj"),
        ("AbramsGlass", "abrams_glass", ROOT / "Assets/approved/trellis_cupola_d_glass.obj"),
        ("LeopardBase", "leopard_base", ROOT / "Assets/approved/trellis_cupola_e_base.obj"),
        ("LeopardGlass", "leopard_glass", ROOT / "Assets/approved/trellis_cupola_e_glass.obj"),
        ("ChallengerBase", "challenger_base", ROOT / "Assets/approved/trellis_cupola_f_base.obj"),
        ("ChallengerGlass", "challenger_glass", ROOT / "Assets/approved/trellis_cupola_f_glass.obj"),
        ("T80BvmBase", "t80bvm_base", ROOT / "Assets/approved/trellis_cupola_g_base.obj"),
        ("T80BvmGlass", "t80bvm_glass", ROOT / "Assets/approved/trellis_cupola_g_glass.obj"),
        ("T90ADriverHatchBase", "t90a_driver_hatch_base", ROOT / "Assets/approved/trellis_t90a_driver_hatch_base.obj"),
        ("T90ADriverHatchGlass", "t90a_driver_hatch_glass", ROOT / "Assets/approved/trellis_t90a_driver_hatch_glass.obj"),
    ]
    for prop, short, path in entries:
        v, n, uv, i = parse_obj_with_uv_wn(path)
        out.extend(emit_entry(prop, short, hashlib.sha256(path.read_bytes()).hexdigest().upper(), v, n, uv, i))

    dv, dn, duv, di = make_hidden_door_box()
    out.extend(emit_entry("HiddenDoor", "door", "0" * 64, dv, dn, duv, di))

    out.append("}")
    (ROOT / "CupolaMeshData.cs").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("Wrote multi-variant CupolaMeshData.cs successfully.")


if __name__ == "__main__":
    main()
