"""Approved OBJ bytes -> embedded mesh data. No regeneration or coordinate changes.
One vertex per v//vn pair, first-use order; preserve OBJ triangle order and winding.
Run: py -I Tools/obj_to_cs.py [--check]
"""
from pathlib import Path
import hashlib, sys, struct
ROOT = Path(__file__).resolve().parents[1]

def parse(path):
    positions, normals, pairs, vertices, ns, indices = [], [], {}, [], [], []
    for line in path.read_text().splitlines():
        p = line.split()
        if not p: continue
        if p[0] == 'v': positions.append(tuple(map(float, p[1:])))
        elif p[0] == 'vn': normals.append(tuple(map(float, p[1:])))
        elif p[0] == 'f':
            assert len(p) == 4
            for corner in p[1:]:
                v, n = map(int, corner.split('//')); key = (v, n)
                assert 1 <= v <= len(positions) and 1 <= n <= len(normals)
                if key not in pairs:
                    pairs[key] = len(vertices); vertices.append(positions[v-1]); ns.append(normals[n-1])
                indices.append(pairs[key])
    return vertices, ns, indices

def main():
    out = ['// <auto-generated> Tools/obj_to_cs.py; approved exports, metres, Y up, +Z forward.',
           'namespace SprocketCupolas;',
           'internal sealed record CupolaData(string Name, string ObjSha256, string DataSha256, float[] Positions, float[] Normals, int[] Indices, float[] Bounds);',
           'internal static class CupolaMeshData {']
    icon = ROOT/'Assets/approved/t90a-cupola-icon.png'
    out.append('internal const string IconSha256 = "'+hashlib.sha256(icon.read_bytes()).hexdigest().upper()+'";')
    for name in ('base', 'door'):
        path = ROOT/f'Assets/approved/t90a_cupola_{name}.obj'
        verts, normals, inds = parse(path)
        pos = sum((list(v) for v in verts), []); ns = sum((list(v) for v in normals), [])
        bounds = [f(v[i] for v in verts) for f in (min, max) for i in range(3)]
        binary = struct.pack('<'+'f'*(len(pos)+len(ns))+'i'*len(inds), *pos, *ns, *inds)
        out.append(f'internal static readonly CupolaData {name.title()} = new("{name}", "{hashlib.sha256(path.read_bytes()).hexdigest().upper()}", "{hashlib.sha256(binary).hexdigest().upper()}",')
        for a, ty in ((pos,'float'),(ns,'float'),(inds,'int'),(bounds,'float')):
            vals = ','.join(format(v,'.9g')+'f' if ty=='float' else str(v) for v in a)
            out.append(f'new {ty}[] {{'+vals+'}'+(');' if a is bounds else ','))
        print(f'{name}: {len(verts)} vertices, {len(inds)//3} triangles')
    out.append('}')
    text = '\n'.join(out)+'\n'; target = ROOT/'CupolaMeshData.cs'
    if '--check' in sys.argv: assert target.read_text() == text, 'embedded data is stale'
    else: target.write_text(text, encoding='utf-8', newline='\n')

if __name__ == '__main__': main()
